// Written from scratch from the kit spec (competition.yaml + vendor/makefun-site/README.md):
// run(input) returns, for one case's { site, templates, files }, exactly the output tree
// makefun-site 1.0.0's build returns, as a JSON object of path -> text. No cross-case state:
